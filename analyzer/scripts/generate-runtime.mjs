import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Keep the vendored baseline untouched. Generate a statically imported module;
// no eval, browser globals, or DOM shims are required at runtime.
const root = new URL('../', import.meta.url);
const original = await readFile(new URL('legacy/src/game2.js', root), 'utf8');
const hash = createHash('sha256').update(original).digest('hex');
if (hash !== 'c5047a4f807a9130bd985f94781c77f22617ea9108b7a97f5e96499ff3b0c81c') {
  throw new Error('Upstream engine changed. Review the extraction before regenerating.');
}
let source = original.slice(original.indexOf('var kicker, lastKicker'));
source = source.replace(/export /g, '').replace(/u\.qp\(\)\s*$/, '');
// The new UI records bounded playback samples itself, rather than retaining
// every player's coordinates for every tick in the legacy heatmap arrays.
source = source.replace(
  'if (b[i].H != null) playerPos[match.length - 1][playerList.indexOf(b[i].w)].push({ x: b[i].H.a.x, y: b[i].H.a.y });',
  '// Position sampling is owned by the standalone adapter.',
);
const adapter = await readFile(new URL('src/engine/runtime-adapter.inc', root), 'utf8');
// Preserve identity and coordinates on the analyzer's existing spatial events.
source = source.replaceAll('player: d.w,', 'player: d.w, playerId: d.V, team: d.ea.w.toLowerCase(),');
source = source.replace('player: lastKicker.name,', 'player: lastKicker.name, playerId: lastKicker.id, team: lastKicker.team.toLowerCase(),');
source = source.replaceAll('team: d.ea.w\n', 'team: d.ea.w, id: d.V, position: { x: ball.x, y: ball.y }\n');
source = source.replace('toucher = { name: b[i].w, team: b[i].ea.w };', 'toucher = { name: b[i].w, team: b[i].ea.w, id: b[i].V, position: { x: d[0].a.x, y: d[0].a.y } };');
source = source.replace('match[match.length - 1].passes.push(lastToucher.name);', 'match[match.length - 1].passes.push({ player: lastToucher.name, playerId: lastToucher.id, team: lastToucher.team.toLowerCase(), lastShot: lastToucher.position, shot: { x: ball.x, y: ball.y } });');
await writeFile(new URL('src/engine/vendor-runtime.js', root),
  '// Generated by scripts/generate-runtime.mjs; do not edit.\n' +
  '// Derived from the pinned upstream game2.js; see legacy/LICENSE.MD and upstream.json.\n' +
  'export function createRuntime(inflateRaw) {\n' +
  'const pako = { inflateRaw };\n' +
  'const window = { performance: { now: () => 0 } };\n' +
  source + '\n' + adapter + '\n}\n');
